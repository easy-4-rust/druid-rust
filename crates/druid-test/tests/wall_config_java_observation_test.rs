use druid_rdbc::governance::wall::WallConfig;
use std::collections::BTreeMap;

fn oracle() -> BTreeMap<&'static str, &'static str> {
    include_str!("fixtures/wall_config_kernel/java-observations.tsv")
        .lines()
        .map(|line| line.split_once('\t').expect("key and value"))
        .collect()
}

