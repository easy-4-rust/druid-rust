#[test]
fn every_bundled_java_rule_set_matches_kernel() {
    let expected = oracle();
    for dialect in ["clickhouse", "mysql", "oracle", "postgres", "sqlserver"] {
        let config = WallConfig::with_config_dir(format!("META-INF/druid/wall/{dialect}"));
        assert_eq!(
            config.deny_functions.join(","),
            expected[format!("{dialect}.denyFunctions").as_str()],
            "{dialect}.denyFunctions"
        );
        assert_eq!(
            config.deny_tables.join(","),
            expected[format!("{dialect}.denyTables").as_str()],
            "{dialect}.denyTables"
        );
        assert_eq!(
            config.deny_schemas.join(","),
            expected[format!("{dialect}.denySchemas").as_str()],
            "{dialect}.denySchemas"
        );
        assert_eq!(
            config.deny_variants.join(","),
            expected[format!("{dialect}.denyVariants").as_str()],
            "{dialect}.denyVariants"
        );
        assert_eq!(
            config.deny_objects.join(","),
            expected[format!("{dialect}.denyObjects").as_str()],
            "{dialect}.denyObjects"
        );
        assert_eq!(
            config.permit_functions.join(","),
            expected[format!("{dialect}.permitFunctions").as_str()],
            "{dialect}.permitFunctions"
        );
        assert_eq!(
            config.permit_tables.join(","),
            expected[format!("{dialect}.permitTables").as_str()],
            "{dialect}.permitTables"
        );
        assert_eq!(
            config.permit_schemas.join(","),
            expected[format!("{dialect}.permitSchemas").as_str()],
            "{dialect}.permitSchemas"
        );
        assert_eq!(
            config.permit_variants.join(","),
            expected[format!("{dialect}.permitVariants").as_str()],
            "{dialect}.permitVariants"
        );
        assert_eq!(
            config.read_only_tables.join(","),
            expected[format!("{dialect}.readOnlyTables").as_str()],
            "{dialect}.readOnlyTables"
        );
    }
}
