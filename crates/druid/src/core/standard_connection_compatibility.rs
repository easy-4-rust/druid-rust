//! Standard Connection 到 Task 6 transitional Physical SPI 的私有建连适配。

use super::{
    ExecResult, PhysicalConnection, PhysicalConnectionCapabilities, RdbcError, Row, SqlWarning,
    StatementGeneratedKeys, Value,
};

/// 仅在旧 physical-connect Filter 链进入 standard holder 前存在的私有适配器。
pub(crate) struct StandardConnectionCompatibility {
    connection: Option<Box<dyn druid_rdbc::connection::Connection>>,
    auto_commit: Option<bool>,
    read_only: Option<bool>,
    catalog: Option<Option<String>>,
    schema: Option<Option<String>>,
    warnings_supported: bool,
    discarded: bool,
}

impl StandardConnectionCompatibility {
    pub(crate) async fn new(
        mut connection: Box<dyn druid_rdbc::connection::Connection>,
    ) -> Result<Self, RdbcError> {
        let auto_commit = optional_standard_state(connection.auto_commit())?;
        let read_only = optional_standard_state(connection.read_only())?;
        let catalog = optional_standard_state(connection.catalog())?;
        let schema = optional_standard_state(connection.schema())?;
        let warnings_supported = optional_standard_state(connection.warnings().await)?.is_some();
        Ok(Self {
            connection: Some(connection),
            auto_commit,
            read_only,
            catalog,
            schema,
            warnings_supported,
            discarded: false,
        })
    }

    pub(crate) fn into_standard(
        mut self,
    ) -> Result<Box<dyn druid_rdbc::connection::Connection>, RdbcError> {
        self.connection.take().ok_or(RdbcError::ConnectionDiscarded)
    }

    fn connection_mut(
        &mut self,
    ) -> Result<&mut (dyn druid_rdbc::connection::Connection + 'static), RdbcError> {
        self.connection
            .as_deref_mut()
            .ok_or(RdbcError::ConnectionDiscarded)
    }

    fn connection_ref(
        &self,
    ) -> Result<&(dyn druid_rdbc::connection::Connection + 'static), RdbcError> {
        self.connection
            .as_deref()
            .ok_or(RdbcError::ConnectionDiscarded)
    }
}

#[async_trait::async_trait]
impl PhysicalConnection for StandardConnectionCompatibility {
    async fn exec(&mut self, sql: &str, params: Vec<Value>) -> Result<ExecResult, RdbcError> {
        if !params.is_empty() {
            return Err(RdbcError::InvalidArgument(
                "standard compatibility update does not accept bind parameters".to_string(),
            ));
        }
        let mut statement = self
            .connection_mut()?
            .create_statement(druid_rdbc::statement::StatementOptions::default())
            .await?;
        let count = statement
            .execute_update(sql, druid_rdbc::statement::GeneratedKeys::None)
            .await?;
        statement.close().await?;
        Ok(ExecResult {
            rows_affected: u64::try_from(count).unwrap_or_default(),
            last_insert_id: None,
            row_count: None,
        })
    }

    async fn execute(
        &mut self,
        sql: &str,
        params: Vec<Value>,
        generated_keys: StatementGeneratedKeys,
    ) -> Result<Vec<super::StatementExecuteResult>, RdbcError> {
        if !params.is_empty() {
            return Err(RdbcError::InvalidArgument(
                "standard compatibility execute does not accept bind parameters".to_string(),
            ));
        }
        let generated_keys = match generated_keys {
            StatementGeneratedKeys::None => druid_rdbc::statement::GeneratedKeys::None,
            StatementGeneratedKeys::AutoGeneratedKeys(_) => {
                druid_rdbc::statement::GeneratedKeys::ReturnGeneratedKeys
            }
            StatementGeneratedKeys::ColumnIndexes(indexes) => {
                let indexes = indexes
                    .into_iter()
                    .map(|index| druid_rdbc::result_set::ColumnIndex::try_from(i64::from(index)))
                    .collect::<Result<Vec<_>, _>>()?;
                druid_rdbc::statement::GeneratedKeys::ColumnIndexes(indexes)
            }
            StatementGeneratedKeys::ColumnNames(names) => {
                druid_rdbc::statement::GeneratedKeys::ColumnNames(names)
            }
        };
        let mut statement = self
            .connection_mut()?
            .create_statement(druid_rdbc::statement::StatementOptions::default())
            .await?;
        let results = statement.execute(sql, generated_keys).await?;
        statement.close().await?;
        results
            .into_iter()
            .map(|result| match result {
                druid_rdbc::statement::ExecutionResult::UpdateCount(count) => {
                    Ok(super::StatementExecuteResult::Update(ExecResult {
                        rows_affected: u64::try_from(count).unwrap_or_default(),
                        last_insert_id: None,
                        row_count: None,
                    }))
                }
                druid_rdbc::statement::ExecutionResult::ResultSet(_) => {
                    Err(RdbcError::UnsupportedOperation {
                        operation: "standard_compatibility_generic_result_set",
                    })
                }
            })
            .collect()
    }

    async fn fetch(&mut self, sql: &str, params: Vec<Value>) -> Result<Vec<Row>, RdbcError> {
        let mut statement = self
            .connection_mut()?
            .create_statement(druid_rdbc::statement::StatementOptions::default())
            .await?;
        let mut result_set = statement.execute_values(sql, params).await?;
        let rows = Vec::new();
        if result_set.next().await? {
            return Err(RdbcError::UnsupportedOperation {
                operation: "standard_compatibility_eager_row_width",
            });
        }
        result_set.close().await?;
        statement.close().await?;
        Ok(rows)
    }

    async fn begin(&mut self) -> Result<(), RdbcError> {
        self.set_auto_commit(false).await
    }

    async fn commit(&mut self) -> Result<(), RdbcError> {
        self.connection_mut()?.commit().await
    }

    async fn rollback(&mut self) -> Result<(), RdbcError> {
        self.connection_mut()?.rollback().await
    }

    async fn ping(&mut self) -> Result<(), RdbcError> {
        if self.connection_mut()?.is_valid(1).await? {
            Ok(())
        } else {
            Err(RdbcError::ConnectionDiscarded)
        }
    }

    async fn close(&mut self) -> Result<(), RdbcError> {
        self.connection_mut()?.close().await
    }

    fn is_closed(&self) -> bool {
        self.connection_ref()
            .and_then(druid_rdbc::connection::Connection::is_closed)
            .unwrap_or(true)
    }

    fn capabilities(&self) -> PhysicalConnectionCapabilities {
        let capabilities = self
            .connection_ref()
            .map(druid_rdbc::connection::Connection::capabilities)
            .unwrap_or_default();
        PhysicalConnectionCapabilities {
            transactions: capabilities.transactions,
            savepoints: capabilities.savepoints,
            auto_commit: self.auto_commit.is_some(),
            read_only: self.read_only.is_some(),
            transaction_isolation: false,
            holdability: false,
            clear_warnings: self.warnings_supported,
            catalog: self.catalog.is_some(),
            schema: self.schema.is_some(),
        }
    }

    fn auto_commit(&self) -> bool {
        self.auto_commit.unwrap_or(false)
    }

    async fn set_auto_commit(&mut self, auto_commit: bool) -> Result<(), RdbcError> {
        if self.auto_commit.is_none() {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_set_auto_commit",
            });
        }
        self.connection_mut()?.set_auto_commit(auto_commit).await?;
        self.auto_commit = Some(auto_commit);
        Ok(())
    }

    fn read_only(&self) -> bool {
        self.read_only.unwrap_or(false)
    }

    async fn set_read_only(&mut self, read_only: bool) -> Result<(), RdbcError> {
        if self.read_only.is_none() {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_set_read_only",
            });
        }
        self.connection_mut()?.set_read_only(read_only).await?;
        self.read_only = Some(read_only);
        Ok(())
    }

    async fn warnings(&mut self) -> Result<Option<SqlWarning>, RdbcError> {
        if !self.warnings_supported {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_warnings",
            });
        }
        self.connection_mut()?.warnings().await
    }

    async fn clear_warnings(&mut self) -> Result<(), RdbcError> {
        if !self.warnings_supported {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_clear_warnings",
            });
        }
        self.connection_mut()?.clear_warnings().await
    }

    fn mark_discarded(&mut self) {
        self.discarded = true;
    }

    fn is_discarded(&self) -> bool {
        self.discarded
    }

    fn catalog(&self) -> Option<&str> {
        self.catalog.as_ref().and_then(|catalog| catalog.as_deref())
    }

    async fn set_catalog(&mut self, catalog: &str) -> Result<(), RdbcError> {
        if self.catalog.is_none() {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_set_catalog",
            });
        }
        self.connection_mut()?.set_catalog(Some(catalog)).await?;
        self.catalog = Some(Some(catalog.to_string()));
        Ok(())
    }

    fn schema(&self) -> Option<&str> {
        self.schema.as_ref().and_then(|schema| schema.as_deref())
    }

    async fn set_schema(&mut self, schema: &str) -> Result<(), RdbcError> {
        if self.schema.is_none() {
            return Err(RdbcError::UnsupportedOperation {
                operation: "connection_set_schema",
            });
        }
        self.connection_mut()?.set_schema(Some(schema)).await?;
        self.schema = Some(Some(schema.to_string()));
        Ok(())
    }

    fn driver_name(&self) -> &str {
        "druid-standard"
    }
}

fn optional_standard_state<T>(result: Result<T, RdbcError>) -> Result<Option<T>, RdbcError> {
    match result {
        Ok(value) => Ok(Some(value)),
        Err(error)
            if matches!(
                error.kind(),
                druid_rdbc::error::RdbcErrorKind::UnsupportedOperation
                    | druid_rdbc::error::RdbcErrorKind::SqlFeatureNotSupported
            ) =>
        {
            Ok(None)
        }
        Err(error) => Err(error),
    }
}
